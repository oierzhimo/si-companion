def main() -> None:
    if CANDIDATES_PATH.exists() and not BACKUP_PATH.exists():
        shutil.copy2(CANDIDATES_PATH, BACKUP_PATH)

    seed_rows = load_jsonl(BACKUP_PATH if BACKUP_PATH.exists() else CANDIDATES_PATH)
    heldout_rows = load_jsonl(HELDOUT_PATH)
    heldout_norms = {norm(r.get("prompt", "")) for r in heldout_rows}

    approved_rows: list[dict] = []
    seen_insts: set[str] = set()

    # 1. Review and approve original 30 seeds
    for r in seed_rows:
        ni = norm(r["instruction"])
        assert ni not in heldout_norms, f"Seed leaked heldout: {r['id']}"
        assert ni not in seen_insts, f"Duplicate seed: {r['id']}"
        seen_insts.add(ni)
        r_copy = dict(r)
        r_copy["review_status"] = "approved"
        approved_rows.append(r_copy)

    # 2. Add curated new rows
    new_tuples = build_samples()
    idx = 1
    for inst, inp, out, cat, prov in new_tuples:
        ni = norm(inst)
        if ni in heldout_norms:
            raise ValueError(f"Leakage detected vs heldout: {inst}")
        if ni in seen_insts:
            raise ValueError(f"Duplicate instruction detected: {inst}")
        seen_insts.add(ni)
        approved_rows.append(
            {
                "id": f"curated-{idx:03d}",
                "instruction": inst.strip(),
                "input": inp.strip(),
                "output": out.strip(),
                "category": cat,
                "provenance": prov,
                "review_status": "approved",
            }
        )
        idx += 1

    # Write approved style_candidates.jsonl
    with CANDIDATES_PATH.open("w", encoding="utf-8") as f:
        for row in approved_rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    cats = {}
    for r in approved_rows:
        cats[r["category"]] = cats.get(r["category"], 0) + 1
    print(f"Wrote {len(approved_rows)} approved rows to {CANDIDATES_PATH}")
    print("Categories:", cats)


if __name__ == "__main__":
    main()
